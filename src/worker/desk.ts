import type { Desk } from "../shared/desk";

/**
 * Пояснення для моделей у режимі акцій. Входи моделей однакові для обох режимів, тож поля з назвою btc
 * тут означають орієнтир ринку; інструкції писались для крипто, і цей абзац їх уточнює.
 */
export function stocksNote(leader: string): string {
  return `
Режим акцій. Інструменти тут — безстрокові USDT-контракти Bybit на акції та ETF США, а не криптовалюти. Де в інструкції чи правилі йдеться про монети, читай «акції».
Орієнтир ринку — ${leader}. Поля btc, btc_trend_4h і btcHoldPct у вхідних даних стосуються саме його, а не біткоїна; домінації BTC та індексу страху і жадібності тут немає.
Основна сесія NYSE і Nasdaq: 9:30–16:00 за Нью-Йорком. Поза нею ліквідність контракту низька й ціна майже стоїть, тож свічки поза сесією малі й з малим обсягом, а звіти компаній і макродані США дають гепи на відкритті.
Бектест і базові частоти в правилах рахувались на криптовалютах; для акцій вони не перевірені, тож не спирайся на ці числа як на доведені.
Фандинг і відкритий інтерес стосуються контракту Bybit, а не самої акції.`;
}

/** Системний промпт агента з уточненням для режиму. Для крипто промпт не змінюється. */
export function forDesk(system: string, desk: Desk, leader: string): string {
  return desk === "crypto" ? system : `${system}\n${stocksNote(leader)}`;
}
